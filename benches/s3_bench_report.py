#!/usr/bin/env python3
"""
Turn a benches/s3_bench.py run into Markdown tables (time, memory, CPU, cost model).

Usage:
  benches/.venv/bin/python benches/s3_bench_report.py                 # latest run
  benches/.venv/bin/python benches/s3_bench_report.py <run-id> --price 0.145 --vcpus 4

The cost model is deliberately simple and every input is a flag:

  capacity per instance [tiles/s] = vcpus * target_util * core_factor / cpu_seconds_per_tile
  instances                      = ceil(load / capacity)
  monthly cost                   = instances * price_per_hour * 730

`core_factor` converts CPU-seconds measured on the benchmark machine into CPU-seconds on
one vCPU of the target instance (0.5 = a vCPU does half the work of a benchmark core).
It is applied to both servers, so it changes absolute cost but not the ratio.
"""

from __future__ import annotations

import argparse
import json
import math
import statistics
from pathlib import Path

RESULTS = Path(__file__).resolve().parent / "results" / "s3"
SERVERS = ["cogzilla", "titiler"]


def load(run: Path, name: str, default=None):
    p = run / name
    return json.loads(p.read_text()) if p.exists() else default


def med(xs):
    xs = [x for x in xs if x is not None]
    return statistics.median(xs) if xs else None


def fmt(x, nd=1, suffix=""):
    if x is None:
        return "-"
    if isinstance(x, float) and x >= 100:
        return f"{x:,.0f}{suffix}"
    return f"{x:,.{nd}f}{suffix}"


def ratio(a, b, nd=1):
    if not a or not b:
        return "-"
    return f"{a / b:.{nd}f}x"


def table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" if i == 0 else "--:" for i in range(len(headers))) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("run_id", nargs="?")
    ap.add_argument("--instance", default="c7g.xlarge")
    ap.add_argument("--vcpus", type=int, default=4)
    ap.add_argument("--ram-gib", type=float, default=8)
    ap.add_argument("--price", type=float, default=0.145, help="on-demand USD/hour")
    ap.add_argument("--core-factor", type=float, default=0.5)
    ap.add_argument("--target-util", type=float, default=0.6)
    ap.add_argument("--loads", default="100,1000,5000")
    ap.add_argument("--get-price", type=float, default=0.0004, help="USD per 1,000 S3 GET requests")
    ap.add_argument("--hot-cost-concurrency", type=int, default=8)
    ap.add_argument("--cogzilla-hot-from", help="run id of an extra cogzilla-only hot run (e.g. larger --cache-mb)")
    args = ap.parse_args()

    if args.run_id:
        run = RESULTS / args.run_id
    else:
        run = max((d for d in RESULTS.iterdir() if (d / "meta.json").exists() and not d.name.startswith("trial")),
                  key=lambda d: d.stat().st_mtime)
    meta = load(run, "meta.json")
    cm = load(run, "cold_miss.json", [])
    hot = load(run, "hot.json", [])
    mem = load(run, "memory.json", [])
    parity = load(run, "parity.json", [])
    s3io = load(run, "s3io_gdal.json", {})
    workloads = list(meta["workloads"])
    hot_big, mem_big, big_mb = [], [], None
    if args.cogzilla_hot_from:
        xr = RESULTS / args.cogzilla_hot_from
        hot_big = [r for r in load(xr, "hot.json", []) if r["server"] == "cogzilla"]
        mem_big = [m for m in load(xr, "memory.json", []) if m["server"] == "cogzilla"]
        big_mb = load(xr, "meta.json")["config"]["cogzilla_cache_mb"]
    base_mb = meta["config"]["cogzilla_cache_mb"]
    out = []
    P = out.append

    P(f"<!-- generated by s3_bench_report.py from run {run.name} -->\n")
    P("## Workloads\n")
    P(table(["workload", "what", "zooms", "tiles"],
            [[f"`{w}`", m["desc"], f"{m['zooms'][0]}-{m['zooms'][1]}", m["n_tiles"]]
             for w, m in meta["workloads"].items()]))

    if parity:
        P("\n## Output parity (same request, both servers)\n")
        P(table(["workload", "tiles compared", "PSNR min (dB)", "PSNR median (dB)", "mask agreement (min)"],
                [[f"`{r['workload']}`", r["tiles"], r["psnr_db_min"], r["psnr_db_median"],
                  f"{r['mask_agreement_min'] * 100:.2f}%"] for r in parity]))

    def agg(phase, w, s, key):
        return med([r.get(key) for r in cm if r["phase"] == phase and r["workload"] == w and r["server"] == s])

    for phase, title in [("cold", "Cold: fresh process, first touch (concurrency %d)"),
                         ("miss", "Miss: warm process, never-seen tiles (concurrency %d)")]:
        if not any(r["phase"] == phase for r in cm):
            continue
        P("\n## " + title % meta["config"]["cold_concurrency"] + "\n")
        P("Median across repetitions. Latency in ms.\n")
        hdr = ["workload", "server"] + (["first request"] if phase == "cold" else []) + \
              ["p50", "p90", "p99", "tiles/s", "CPU-s / 1k tiles", "S3 GETs / tile", "S3 KiB / tile"]
        rows = []
        for w in workloads:
            for s in SERVERS:
                gets = agg(phase, w, s, "s3_gets_per_tile")
                kb = agg(phase, w, s, "s3_kb_per_tile")
                if s == "titiler" and phase == "miss" and w in s3io:
                    gets, kb = s3io[w]["s3_gets_per_tile"], s3io[w]["s3_kb_per_tile"]
                row = [f"`{w}`", s]
                if phase == "cold":
                    row.append(fmt(agg(phase, w, s, "first_ms"), 0))
                row += [fmt(agg(phase, w, s, k), 0) for k in ("p50_ms", "p90_ms", "p99_ms")]
                row += [fmt(agg(phase, w, s, "tiles_per_s")), fmt(agg(phase, w, s, "cpu_s_per_1k")),
                        fmt(gets, 2), fmt(kb, 0)]
                rows.append(row)
        P(table(hdr, rows))

    if hot:
        P("\n## Hot: the same tiles requested repeatedly (oha, closed loop)\n")
        variants = [(f"cogzilla ({base_mb} MiB cache)", [r for r in hot if r["server"] == "cogzilla"])]
        if hot_big:
            variants.append((f"cogzilla ({big_mb} MiB cache)", hot_big))
        variants.append(("TiTiler", [r for r in hot if r["server"] == "titiler"]))
        rows = []
        for w in workloads:
            for c in meta["config"]["hot_concurrency"]:
                for label, data in variants:
                    r = next((x for x in data if x["workload"] == w and x["concurrency"] == c), None)
                    if r:
                        rows.append([f"`{w}`", c, label, fmt(r["rps"]), fmt(r["p50_ms"]), fmt(r["p90_ms"]),
                                     fmt(r["p99_ms"]), fmt(r["cpu_cores_used"], 2), fmt(r["cpu_s_per_1k"], 2),
                                     fmt(r.get("rss_peak_mb"), 0)])
        P(table(["workload", "c", "server", "req/s", "p50 ms", "p90 ms", "p99 ms", "cores busy",
                 "CPU-s / 1k", "RSS MiB"], rows))
        allhot = hot + hot_big
        bad = [r for r in allhot if set(r["statuses"]) - {"200"} or r["errors"]]
        P(f"\nNon-200 responses or client errors in hot runs: {len(bad)} of {len(allhot)} steps."
          + ("" if not bad else " " + "; ".join(f"{r['server']}/{r['workload']}/c{r['concurrency']}: {r['statuses']} {r['errors']}" for r in bad)))

    # ---------------------------------------------------------------- CPU per tile
    cpu = {}
    P("\n## CPU cost per tile\n")
    P(f"CPU-seconds (user+system, whole process tree) per 1,000 tiles. `miss` is the median of the miss "
      f"passes; `hot` is the c={args.hot_cost_concurrency} load step.\n")
    rows = []
    for regime in ("miss", "hot"):
        for w in workloads:
            vals = {}
            for s in SERVERS:
                if regime == "miss":
                    vals[s] = agg("miss", w, s, "cpu_s_per_1k")
                else:
                    src = hot_big if (s == "cogzilla" and hot_big) else hot
                    vals[s] = med([r["cpu_s_per_1k"] for r in src if r["server"] == s and r["workload"] == w
                                   and r["concurrency"] == args.hot_cost_concurrency])
            if None in vals.values():
                continue
            cpu.setdefault(regime, {})[w] = vals
            rows.append([regime, f"`{w}`", fmt(vals["cogzilla"], 2), fmt(vals["titiler"], 2),
                         ratio(vals["titiler"], vals["cogzilla"]),
                         fmt(1000 / vals["cogzilla"], 0), fmt(1000 / vals["titiler"], 1)])
        if regime in cpu:
            m = {s: statistics.mean(v[s] for v in cpu[regime].values()) for s in SERVERS}
            cpu[regime]["__mix__"] = m
            rows.append([regime, "**equal mix**", f"**{fmt(m['cogzilla'], 2)}**", f"**{fmt(m['titiler'], 2)}**",
                         f"**{ratio(m['titiler'], m['cogzilla'])}**",
                         f"**{fmt(1000 / m['cogzilla'], 0)}**", f"**{fmt(1000 / m['titiler'], 1)}**"])
    P(table(["regime", "workload", "cogzilla CPU-s/1k", "TiTiler CPU-s/1k", "TiTiler / cogzilla",
             "cogzilla tiles/s per core", "TiTiler tiles/s per core"], rows))

    # ---------------------------------------------------------------- memory
    per_worker_mb = None
    if mem:
        P("\n## Memory (whole process tree, RSS)\n")
        def get(data, srv, stage, k="rss_mb"):
            return next((m.get(k) for m in data if m["server"] == srv and m["stage"] == stage), None)
        cold_peak = {x: max((r.get("rss_peak_mb", 0) for r in cm if r["server"] == x), default=None) for x in SERVERS}
        hdr = ["", f"cogzilla ({base_mb} MiB cache)"]
        cols = [(mem, "cogzilla")]
        if mem_big:
            hdr.append(f"cogzilla ({big_mb} MiB cache)")
            cols.append((mem_big, "cogzilla"))
        hdr.append(f"TiTiler ({meta['config']['titiler_workers']} workers)")
        cols.append((mem, "titiler"))
        rows = []
        for label, stage in [("idle after start", "idle"), ("steady state after load", "steady_after_load"),
                             ("peak during hot phase", "peak_overall")]:
            rows.append([label] + [fmt(get(d, x, stage), 0, " MiB") for d, x in cols])
        row = ["peak during cold/miss phase", fmt(cold_peak["cogzilla"], 0, " MiB")]
        if mem_big:
            row.append("-")
        row.append(fmt(cold_peak["titiler"], 0, " MiB"))
        rows.append(row)
        P(table(hdr, rows))
        peak_tt = max(get(mem, "titiler", "peak_overall") or 0, cold_peak["titiler"] or 0)
        per_worker_mb = peak_tt / meta["config"]["titiler_workers"]
        P(f"\nTiTiler peak RSS per worker: about {per_worker_mb:,.0f} MiB; idle per worker: about "
          f"{(get(mem, 'titiler', 'idle') or 0) / meta['config']['titiler_workers']:,.0f} MiB.")

    # ---------------------------------------------------------------- cost
    if cpu:
        loads = [int(x) for x in args.loads.split(",")]
        monthly = args.price * 730
        P("\n## Cost model\n")
        P(f"Assumptions: `{args.instance}` ({args.vcpus} vCPU, {args.ram_gib:g} GiB) at ${args.price}/h on-demand "
          f"= ${monthly:,.2f}/month (730 h); target CPU utilisation {args.target_util:.0%}; "
          f"core factor {args.core_factor} (one vCPU does {args.core_factor:g}x the work of one benchmark-machine core); "
          f"equal mix of the five workloads; compute only.\n")
        P("```\ncapacity per instance = vcpus x util x core_factor / cpu_seconds_per_tile\n"
          "instances             = ceil(load / capacity)\n```\n")
        rows = []
        for regime in cpu:
            m = cpu[regime]["__mix__"]
            cap = {s: args.vcpus * args.target_util * args.core_factor / (m[s] / 1000) for s in SERVERS}
            rows.append([f"{regime}: capacity per instance (tiles/s)", fmt(cap["cogzilla"], 0), fmt(cap["titiler"], 1),
                         ratio(cap["cogzilla"], cap["titiler"])])
            for L in loads:
                n = {s: max(1, math.ceil(L / cap[s])) for s in SERVERS}
                rows.append([f"{regime}: {L:,} tiles/s",
                             f"{n['cogzilla']} x = ${n['cogzilla'] * monthly:,.0f}/mo",
                             f"{n['titiler']} x = ${n['titiler'] * monthly:,.0f}/mo",
                             ratio(n["titiler"], n["cogzilla"])])
        P(table(["", "cogzilla", "TiTiler", "ratio"], rows))
        if per_worker_mb:
            need = per_worker_mb * args.vcpus / 1024
            P(f"\nMemory check: TiTiler at one worker per vCPU needs about {need:.1f} GiB of the instance's "
              f"{args.ram_gib:g} GiB at the measured peak per-worker RSS.")
        # S3 request cost, independent of server compute
        P("\n### S3 GET request cost (only if you own the bucket)\n")
        rows = []
        for w in workloads:
            g = {"cogzilla": agg("miss", w, "cogzilla", "s3_gets_per_tile"),
                 "titiler": s3io.get(w, {}).get("s3_gets_per_tile")}
            if None in g.values():
                continue
            cost = {s: g[s] * 1000 * 730 * 3600 / 1000 * args.get_price for s in SERVERS}
            rows.append([f"`{w}`", fmt(g["cogzilla"], 2), fmt(g["titiler"], 2),
                         f"${cost['cogzilla']:,.0f}", f"${cost['titiler']:,.0f}"])
        P(table(["workload", "cogzilla GETs/tile (miss)", "GDAL GETs/tile (headers warm)",
                 "cogzilla $/mo at 1,000 uncached tiles/s", "TiTiler $/mo at 1,000 uncached tiles/s"], rows))
        P(f"\nAt ${args.get_price} per 1,000 GETs.")

    P("\n## Configuration\n")
    P("```json\n" + json.dumps({k: meta[k] for k in ("machine", "versions", "config")}, indent=1) + "\n```")

    text = "\n".join(out) + "\n"
    (run / "report.md").write_text(text)
    print(text)
    print(f"-> {run / 'report.md'}")


if __name__ == "__main__":
    main()
